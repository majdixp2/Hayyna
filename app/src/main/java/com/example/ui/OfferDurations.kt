//  مثال: listOf(1, 3, 7, 14, 30) يطلع الخيارات:
//        "يوم" ، "3 أيام" ، "أسبوع" ، "أسبوعين" ، "شهر"
//
//  - أضف أو احذف أرقام كما تحب (لازم يكون فيه رقم واحد على الأقل).
//  - الترتيب هنا هو نفس ترتيب الأزرار في التطبيق.
//  - خيار "بدون انتهاء" يظهر دائماً أول شي.
//
