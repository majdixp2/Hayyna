/** اسم المدة بالعربي: 1 -> "يوم" ، 2 -> "يومين" ، 7 -> "أسبوع" ... */
fun durationLabel(days: Int): String = when (days) {
    1 -> "يوم"
    2 -> "يومين"
    7 -> "أسبوع"
    14 -> "أسبوعين"
    30 -> "شهر"
    in 3..10 -> "$days أيام"
    else -> "$days يوم"
}
